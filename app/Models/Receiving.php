<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\SoftDeletes;
use Spatie\Activitylog\Support\LogOptions;
use Spatie\Activitylog\Models\Concerns\LogsActivity;

class Receiving extends Model
{
    use LogsActivity, SoftDeletes;

    protected $fillable = [
        'master_item_id',
        'receive_no',
        'supplier_name',
        'supplier_address',
        'purchase_order_no',
        'delivery_order_no',
        'invoice_no',               // No Invois — KEW.PA-1A header
        'item_description',
        'quantity_ordered',
        'quantity_received',
        'unit_price',               // Harga Seunit
        'total_price',              // Jumlah (auto-computed)
        'status',                   // pending | accepted | rejected
        // Signature block — Pegawai Penerima
        'receiver_name',
        'receiver_position',
        // Signature block — Pegawai Bertanggungjawab
        'technical_officer_name',
        'technical_officer_position',
        'damage_description', // NEW
        'notes',              // NEW
        'rejection_reason',   // set when a receiving is rejected (no asset created)
        'rejected_at',
    ];

    protected $casts = [
        'unit_price'  => 'decimal:2',
        'total_price' => 'decimal:2',
    ];

    // ─── Relations ─────────────────────────────────────────────────────────────

    public function masterItem()
    {
        return $this->belongsTo(MasterItem::class);
    }

    /** Assets generated by this PA-1 — delete of the PA-1 is refused while any exist. */
    public function assets(): HasMany
    {
        return $this->hasMany(Asset::class, 'receiving_id');
    }

    public function getActivitylogOptions(): LogOptions
    {
        return LogOptions::defaults()
            ->logAll()
            ->logOnlyDirty()
            ->dontLogEmptyChanges();
    }
}